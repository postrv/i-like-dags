#!/usr/bin/env node

/**
 * Rebuild the exact browser kernel served by dag-edge.
 *
 * wasm-bindgen's CLI and crate formats are version-coupled. Keep VERSION in
 * sync with crates/dag-wasm/Cargo.toml. The generated artifacts and digest
 * manifest are committed so deployments do not install build tools or fetch
 * code from a CDN.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  copyFileSync,
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const VERSION = "0.2.104";
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const publicDir = join(root, "crates/dag-edge/worker/public");
const standaloneDir = join(here, "dist");
const scratch = mkdtempSync(join(tmpdir(), "dag-wasm-browser-"));

function run(program, args) {
  execFileSync(program, args, { cwd: root, stdio: "inherit" });
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest();
}

try {
  const actual = execFileSync("wasm-bindgen", ["--version"], {
    cwd: root,
    encoding: "utf8",
  }).trim();
  if (actual !== `wasm-bindgen ${VERSION}`) {
    throw new Error(
      `need wasm-bindgen ${VERSION}, found ${actual}; install with ` +
        `cargo install -f wasm-bindgen-cli --version ${VERSION} --locked`,
    );
  }

  run("cargo", [
    "build",
    "--locked",
    "--release",
    "--target",
    "wasm32-unknown-unknown",
    "-p",
    "dag-wasm",
  ]);
  run("wasm-bindgen", [
    join(root, "target/wasm32-unknown-unknown/release/dag_wasm.wasm"),
    "--target",
    "no-modules",
    "--out-dir",
    scratch,
    "--out-name",
    "dag_wasm",
    "--no-modules-global",
    "DagWasm",
    "--omit-default-module-path",
    "--remove-name-section",
    "--remove-producers-section",
  ]);

  mkdirSync(publicDir, { recursive: true });
  mkdirSync(standaloneDir, { recursive: true });
  const wasm = readFileSync(join(scratch, "dag_wasm_bg.wasm"));
  const wasmDigest = sha256(wasm);
  const generatedJs = readFileSync(join(scratch, "dag_wasm.js"), "utf8");
  if (!generatedJs.startsWith("let DagWasm;")) {
    throw new Error("unexpected wasm-bindgen no-modules wrapper");
  }
  const banner =
    `/* Generated by crates/dag-wasm/web/build-browser.mjs with ` +
    `wasm-bindgen ${VERSION}. Do not edit. */\n`;
  // `var` deliberately exposes the generated namespace as `window.DagWasm`.
  // The browser loads this classic script with SRI before calling the kernel.
  const js = Buffer.from(banner + generatedJs.replace("let DagWasm;", "var DagWasm;"), "utf8");

  writeFileSync(join(publicDir, "dag_wasm.js"), js);
  copyFileSync(join(scratch, "dag_wasm_bg.wasm"), join(publicDir, "dag_wasm_bg.wasm"));
  writeFileSync(join(standaloneDir, "dag_wasm.js"), js);
  copyFileSync(join(scratch, "dag_wasm_bg.wasm"), join(standaloneDir, "dag_wasm_bg.wasm"));

  const manifest = `// Generated by build-browser.mjs. Do not edit.\n` +
    `export const DAG_WASM_BINDGEN_VERSION = ${JSON.stringify(VERSION)};\n` +
    `export const DAG_WASM_SHA256_HEX = ${JSON.stringify(wasmDigest.toString("hex"))};\n` +
    `export const DAG_WASM_SHA256_SRI = ${JSON.stringify(`sha256-${wasmDigest.toString("base64")}`)};\n` +
    `export const DAG_WASM_JS_SHA256_SRI = ${JSON.stringify(`sha256-${sha256(js).toString("base64")}`)};\n`;
  writeFileSync(join(here, "browser-kernel.mjs"), manifest);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
